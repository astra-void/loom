// @vitest-environment node
import { mkdirSync, mkdtempSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import type { Plugin } from "vite";
import { afterEach, describe, expect, it } from "vitest";
import { findEntry } from "./html.ts";
import { LUAU_PROJECT_ID, loomLuau } from "./luau-plugin.ts";
import {
	generateLuauProjectModule,
	type LuauFileNode,
	projectFiles,
	readLuauProject,
} from "./luau-project.ts";

let roots: string[] = [];
afterEach(() => {
	for (const root of roots) rmSync(root, { recursive: true, force: true });
	roots = [];
});

/** A throwaway project with `files` (`path → contents`). */
function project(files: Record<string, string>): string {
	const root = mkdtempSync(join(tmpdir(), "loom-luau-"));
	roots.push(root);
	for (const [path, contents] of Object.entries(files)) {
		const file = join(root, path);
		mkdirSync(dirname(file), { recursive: true });
		writeFileSync(file, contents);
	}
	return root;
}

/** The tree without file paths: `name:Class` with children, for terse assertions. */
function shape(node: LuauFileNode): unknown {
	const label = `${node.name}:${node.className}`;
	return node.children ? { [label]: node.children.map(shape) } : label;
}

describe("readLuauProject", () => {
	it("reads the rojo init layout by Rojo's file rules", () => {
		const root = project({
			"src/client/Main.client.luau": "",
			"src/server/Boot.server.lua": "",
			"src/shared/Util.luau": "",
			"src/shared/Widgets/init.luau": "",
			"src/shared/Widgets/Button.luau": "",
			"src/shared/Button.loom.luau": "", // a gallery target, not part of the place
			"src/shared/README.md": "",
			"src/shared/data.json": "",
		});
		expect(shape(readLuauProject(root) as LuauFileNode)).toEqual({
			"DataModel:DataModel": [
				{
					"ReplicatedStorage:ReplicatedStorage": [
						{
							"Shared:Folder": [
								"Util:ModuleScript",
								{ "Widgets:ModuleScript": ["Button:ModuleScript"] },
							],
						},
					],
				},
				{
					"ServerScriptService:ServerScriptService": [
						{ "Server:Folder": ["Boot:Script"] },
					],
				},
				{
					"StarterPlayer:StarterPlayer": [
						{
							"StarterPlayerScripts:StarterPlayerScripts": [
								{ "Client:Folder": ["Main:LocalScript"] },
							],
						},
					],
				},
			],
		});
	});

	it("leaves out the template's folders that are not there", () => {
		const root = project({ "src/client/Main.client.luau": "" });
		const tree = shape(readLuauProject(root) as LuauFileNode);
		expect(JSON.stringify(tree)).not.toContain("ReplicatedStorage");
		expect(JSON.stringify(tree)).toContain("Main:LocalScript");
	});

	it("follows default.project.json, inferring a service's class from its name", () => {
		const root = project({
			"default.project.json": JSON.stringify({
				name: "game",
				tree: {
					$className: "DataModel",
					ReplicatedStorage: { Lib: { $path: "lib" } },
					StarterGui: {
						Hud: {
							$className: "ScreenGui",
							Script: { $path: "hud.client.luau" },
						},
					},
				},
			}),
			"lib/Signal.luau": "return {}",
			"hud.client.luau": "print('hud')",
		});
		const tree = readLuauProject(root) as LuauFileNode;
		expect(shape(tree)).toEqual({
			"DataModel:DataModel": [
				{
					"ReplicatedStorage:ReplicatedStorage": [
						{ "Lib:Folder": ["Signal:ModuleScript"] },
					],
				},
				{
					"StarterGui:StarterGui": [
						{ "Hud:ScreenGui": ["Script:LocalScript"] },
					],
				},
			],
		});
		expect(projectFiles(tree).map((f) => f.slice(root.length))).toEqual([
			"/lib/Signal.luau",
			"/hud.client.luau",
		]);
	});

	it("runs a bare src/ of scripts from StarterPlayerScripts", () => {
		const root = project({ "src/Card.client.luau": "" });
		expect(
			JSON.stringify(shape(readLuauProject(root) as LuauFileNode)),
		).toContain('{"Client:Folder":["Card:LocalScript"]}');
	});

	it("is not a Luau project without Luau scripts", () => {
		expect(
			readLuauProject(project({ "src/main.client.tsx": "" })),
		).toBeUndefined();
		expect(readLuauProject(project({ "README.md": "" }))).toBeUndefined();
	});
});

describe("generateLuauProjectModule", () => {
	it("inlines every script's source", () => {
		const root = project({ "src/shared/Util.luau": "return 'é'" });
		const code = generateLuauProjectModule(readLuauProject(root));
		expect(code).toContain('"source":"return \'é\'"');
		expect(code).toMatch(/^\/\/ generated by loom/);
	});
});

describe("findEntry", () => {
	it("prefers a TypeScript entry over Luau scripts", () => {
		const root = project({
			"src/main.client.ts": "",
			"src/client/Main.client.luau": "",
		});
		expect(findEntry(root)).toBe("/src/main.client.ts");
	});

	it("loads @loom-dev/luau/entry for a Luau project that depends on it", () => {
		const example = join(process.cwd(), "apps/luau-example");
		expect(findEntry(example)).toMatch(
			/^\/@fs\/.*\/packages\/luau\/src\/entry\.ts$/,
		);
	});

	it("asks for @loom-dev/luau when a Luau project cannot reach it", () => {
		const root = project({ "src/client/Main.client.luau": "" });
		expect(() => findEntry(root)).toThrow(/@loom-dev\/luau is not installed/);
	});
});

describe("loomLuau", () => {
	/** The plugin's hooks against `root`, with the watched files collected. */
	function hooks(root: string) {
		const plugin = loomLuau();
		const call = <K extends keyof Plugin>(name: K, ...args: unknown[]) => {
			const hook = plugin[name] as unknown as (...a: unknown[]) => unknown;
			return hook.call(context, ...args);
		};
		const watched: string[] = [];
		const context = { addWatchFile: (file: string) => watched.push(file) };
		call("configResolved", { root });
		return { call, watched };
	}

	it("serves the project, watching every script", () => {
		const root = project({ "src/shared/Util.luau": "return 1" });
		const { call, watched } = hooks(root);
		const id = call("resolveId", LUAU_PROJECT_ID) as string;
		expect(call("load", id)).toContain('"source":"return 1"');
		expect(watched).toEqual([join(root, "src/shared/Util.luau")]);
	});

	it("compiles a *.loom.luau target to a preview export", () => {
		const root = project({ "src/shared/Badge.loom.luau": "print('hi')" });
		const code = hooks(root).call(
			"load",
			join(root, "src/shared/Badge.loom.luau"),
		) as string;
		expect(code).toContain('import { luauPreview } from "@loom-dev/luau"');
		expect(code).toContain(`import { project } from "${LUAU_PROJECT_ID}"`);
		expect(code).toContain(
			'luauPreview("print(\'hi\')", { name: "Badge", project })',
		);
	});

	it("leaves every other module alone", () => {
		const root = project({ "src/App.tsx": "" });
		expect(hooks(root).call("load", join(root, "src/App.tsx"))).toBeUndefined();
	});
});
