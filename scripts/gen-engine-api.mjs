// Writes the runtime's engine reflection tables from `@rbxts/types`:
//
//   packages/runtime/src/engine-enums.ts   every `Enum.<Type>` and its items
//   packages/runtime/src/engine-events.ts  every class's own RBXScriptSignals
//
// loom hand-writes the enums and events it acts on. These tables cover the rest
// of the engine, so library code that reads an enum or connects to an event loom
// never raises still loads, instead of dying on a nil (Fusion, Iris and Vide all
// read enums no preview renders while they build their default-property tables).
//
// usage: node scripts/gen-engine-api.mjs   (reads @rbxts/types from packages/preview)
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repo = join(dirname(fileURLToPath(import.meta.url)), "..");
const require = createRequire(join(repo, "packages/preview/package.json"));
const typesDir = dirname(require.resolve("@rbxts/types/package.json"));
const { version } = JSON.parse(
	readFileSync(join(typesDir, "package.json"), "utf8"),
);
const generated = join(typesDir, "include/generated");
const header = `// Generated by scripts/gen-engine-api.mjs from @rbxts/types ${version}. Do not edit.\n`;

// --- enums -------------------------------------------------------------------

const enumsDts = readFileSync(join(generated, "enums.d.ts"), "utf8");
const enums = [];
for (const block of enumsDts.split(/\n {4}export namespace /).slice(1)) {
	const name = /^(\w+)/.exec(block)[1];
	const items = [...block.matchAll(/Name: "(\w+)";\s*Value: (-?\d+);/g)].map(
		(m) => [m[1], Number(m[2])],
	);
	enums.push([name, items]);
}
enums.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

// One string per enum: `Name` when its value is the previous one plus one
// (counting from 0), `Name=Value` otherwise. Most enums count 0, 1, 2, …, so
// the table stays a fraction of the size of an object per item.
function encode(items) {
	let next = 0;
	return items
		.map(([name, value]) => {
			const word = value === next ? name : `${name}=${value}`;
			next = value + 1;
			return word;
		})
		.join(" ");
}

writeFileSync(
	join(repo, "packages/runtime/src/engine-enums.ts"),
	`${header}
/**
 * Every engine enum, as \`Item Item=Value …\`: an item without \`=Value\` is the
 * previous item's value plus one, and the first counts from 0.
 */
export const ENGINE_ENUMS: Readonly<Record<string, string>> = {
${enums.map(([name, items]) => `\t${name}: ${JSON.stringify(encode(items))},`).join("\n")}
};
`,
);

// --- events ------------------------------------------------------------------

const classesDts = readFileSync(join(generated, "None.d.ts"), "utf8");
const events = [];
for (const m of classesDts.matchAll(
	/\ninterface (\w+) extends \w+ \{\n([\s\S]*?)\n\}/g,
)) {
	const own = [
		...m[2].matchAll(/^ {4}readonly (\w+): RBXScriptSignal\b/gm),
	].map((e) => e[1]);
	if (own.length > 0) events.push([m[1], [...new Set(own)].sort()]);
}
events.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));

writeFileSync(
	join(repo, "packages/runtime/src/engine-events.ts"),
	`${header}
/** Each engine class's own events (not its superclasses'), space-separated. */
export const ENGINE_EVENTS: Readonly<Record<string, string>> = {
${events.map(([name, own]) => `\t${name}: ${JSON.stringify(own.join(" "))},`).join("\n")}
};
`,
);

// Long strings wrap differently by hand than under biome; let it decide.
execFileSync(
	join(repo, "node_modules/.bin/biome"),
	[
		"format",
		"--write",
		"packages/runtime/src/engine-enums.ts",
		"packages/runtime/src/engine-events.ts",
	],
	{ cwd: repo, stdio: "ignore" },
);

console.log(
	`@rbxts/types ${version}: ${enums.length} enums, ${events.length} classes with events`,
);
